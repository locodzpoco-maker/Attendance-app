function generateKeyVariations(id: string): string[] {
  const trimmed = id.trim();
  const lower = trimmed.toLowerCase();
  const res = new Set<string>([trimmed, lower]);
  
  const unpadded = trimmed.replace(/^0+/, "");
  if (unpadded) {
    res.add(unpadded);
    res.add(unpadded.toLowerCase());
  }

  // If starts with id like id22222
  if (lower.startsWith("id")) {
    const withoutId = lower.replace(/^id/i, "");
    res.add(withoutId);
    res.add(withoutId.replace(/^0+/, ""));
  }

  // If purely digits
  const num = parseInt(unpadded || trimmed, 10);
  if (!isNaN(num)) {
    res.add(String(num));
    res.add(String(num).padStart(4, "0"));
    res.add(String(num).padStart(5, "0"));
    res.add(String(num).padStart(8, "0"));
  }

  return Array.from(res);
}

